def test_firmware_mixed_provenance_rejected(contract_test_device):
    """
    Validates that attempting to mix SENSOR_MEASURED and SYNTHETIC in one payload
    violates the Pydantic schema and is rejected with HTTP 422.
    """
    dev = contract_test_device

    invalid_payload = {
        "device_id": dev["device_id"],
        "farm_id": dev["farm_id"],
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "measurements": [
            {
                "sensor_type": "SOIL_MOISTURE",
                "parameter_name": "soil_moisture",
                "calibrated_value": 30.0,
                "data_source": "SENSOR_MEASURED"
            },
            {
                "sensor_type": "SOIL_TEMP",
                "parameter_name": "soil_temperature",
                "calibrated_value": 25.0,
                "data_source": "SYNTHETIC" # Illegal mixed provenance
            }
        ]
    }

    resp = client.post("/api/telemetry/ingest", json=invalid_payload)
    assert resp.status_code == 422
