def test_firmware_telemetry_duplicate_rejection(contract_test_device):
    """
    Validates that retransmitting the exact same telemetry packet returns DUPLICATE status.
    """
    dev = contract_test_device
    timestamp_str = datetime.now(timezone.utc).isoformat()

    payload = {
        "device_id": dev["device_id"],
        "farm_id": dev["farm_id"],
        "sequence_number": 999,
        "timestamp": timestamp_str,
        "measurements": [
            {
                "sensor_type": "SOIL_MOISTURE",
                "parameter_name": "soil_moisture",
                "calibrated_value": 40.0,
                "data_source": "SENSOR_MEASURED",
                "quality": "GOOD"
            }
        ]
    }

    # First transmission
    resp1 = client.post("/api/telemetry/ingest", json=payload)
    assert resp1.status_code == 201
    assert resp1.json()["status"] in ("SUCCESS", "PROCESSED")

    # Identical replay transmission
    resp2 = client.post("/api/telemetry/ingest", json=payload)
    assert resp2.status_code == 201
    assert resp2.json()["status"] == "DUPLICATE"


